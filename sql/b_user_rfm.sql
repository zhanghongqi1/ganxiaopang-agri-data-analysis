-- ==================================================================
-- b_user_rfm.sql — 用户分层标签（RFM）
-- ⚠️ 模拟数据：仅用于分析方法复现，不代表真实经营结果
-- 口径（详见 docs/指标口径.md）：
--   观察截止日 T = 2025-12-31；样本 = 时间窗内有 ≥1 笔已付款订单的用户
--   R = 最近付款日距 T 天数（越小越好）
--   F = 付款订单数（真实数据高度右偏，采用「F≥2 是否复购」二分）
--   M = 累计支付金额（越大越好）
-- 输出：分层规则、人群占比、人群价值贡献
-- ==================================================================
USE ganxiaopang_db;

-- ------------------------------------------------------------------
-- 1. RFM 原始值 + 分层结果
-- ------------------------------------------------------------------
SELECT
    s.user_id,
    u.province                                          AS 省份,
    u.member_level                                      AS 会员等级,
    u.source                                            AS 注册渠道,
    s.R_最近购买天数,
    s.F_购买频次,
    s.M_累计金额,
    CONCAT(s.R_分, s.F_分, s.M_分)                      AS RFM组合,
    s.人群分层,
    CASE s.人群分层
        WHEN '重要价值客户' THEN '近期活跃+已复购+高额，核心资产：专属客服、新品优先、会员日权益'
        WHEN '重要保持客户' THEN '高频高额但近期沉默：短信/企微召回、老客专属券'
        WHEN '重要发展客户' THEN '近期购买+高客单但未复购：首单后 15 天内二次触达、复购券'
        WHEN '重要挽留客户' THEN '近期活跃且已复购但金额低：组合装提升客单、满减引导'
        WHEN '一般价值客户' THEN '高额一次性购买：防流失，推送同品类新品'
        WHEN '一般发展客户' THEN '新客/低频低额：首购激励、引流款试用'
        WHEN '一般保持客户' THEN '老客低消费：活动触达，性价比商品推荐'
        ELSE '一般挽留客户'
    END                                                 AS 运营建议
FROM v_user_segment s
JOIN dim_users u ON s.user_id = u.user_id
ORDER BY s.M_累计金额 DESC;

-- ------------------------------------------------------------------
-- 2. 人群分层汇总（占比 + 价值贡献）
-- ------------------------------------------------------------------
SELECT
    人群分层,
    用户数,
    人群占比_pct,
    平均R天数,
    平均频次,
    平均金额,
    累计贡献金额,
    贡献占比_pct
FROM v_user_segment_summary;

-- ------------------------------------------------------------------
-- 3. 复购率与消费频次
-- ------------------------------------------------------------------
SELECT
    '复购率' AS 指标,
    CONCAT(复购率_pct, '%') AS 数值,
    CONCAT('复购用户 ', 复购用户数, ' / 购买用户 ', 购买用户数) AS 说明
FROM v_repurchase
UNION ALL
SELECT '人均购买频次', CAST(人均购买频次 AS CHAR), '时间窗内付款订单数 ÷ 购买用户数'
FROM v_repurchase;

-- ------------------------------------------------------------------
-- 4. RFM 分层 × 会员等级交叉（校验分层合理性）
-- ------------------------------------------------------------------
SELECT
    s.人群分层,
    u.member_level                                      AS 会员等级,
    COUNT(*)                                            AS 用户数,
    ROUND(AVG(s.M_累计金额), 2)                          AS 平均金额
FROM v_user_segment s
JOIN dim_users u ON s.user_id = u.user_id
GROUP BY s.人群分层, u.member_level
ORDER BY 平均金额 DESC;

-- ------------------------------------------------------------------
-- 5. 各注册渠道的用户质量（RFM 视角）
-- ------------------------------------------------------------------
SELECT
    u.source                                            AS 注册渠道,
    COUNT(*)                                            AS 用户数,
    ROUND(AVG(s.R_最近购买天数), 0)                      AS 平均R天数,
    ROUND(AVG(s.F_购买频次), 2)                          AS 平均频次,
    ROUND(AVG(s.M_累计金额), 2)                          AS 平均金额,
    ROUND(SUM(CASE WHEN s.人群分层='重要价值客户' THEN 1 ELSE 0 END)
          / COUNT(*) * 100, 2)                          AS 重要价值客户占比_pct
FROM v_user_segment s
JOIN dim_users u ON s.user_id = u.user_id
GROUP BY u.source
ORDER BY 平均金额 DESC;
